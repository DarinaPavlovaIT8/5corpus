"""Одноразовое мерцание силуэта поверх сцены: чистая логика без pygame (легко тестировать).
Запускается действием {"flash": "картинка:метка"}; повторно с той же меткой не срабатывает (метка хранится во флагах)."""

FLASH_TIME = 2.0  # сколько секунд живёт эффект
# (начало, конец, яркость 0..255): три короткие вспышки, потом плавное затухание
BLIPS = ((0.40, 0.52, 230), (0.66, 0.76, 120), (0.92, 1.02, 255))
FADE = (1.15, 2.0)


def alpha(t):
    """Прозрачность силуэта в момент t (секунды от старта эффекта)."""
    for a, b, v in BLIPS:
        if a <= t < b:
            return v
    if FADE[0] <= t < FADE[1]:
        return int(200 * (1 - (t - FADE[0]) / (FADE[1] - FADE[0])))
    return 0
